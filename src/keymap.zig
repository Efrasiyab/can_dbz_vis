const zz = @import("zigzag");

pub const Action = enum {
    quit,
    help,
    connect,
    pause,
    filter,
    pin,
    trace,
    database_only,
    next_tab,
    tab_monitor,
    tab_transmit,
    tab_sent,
    tab_plot,
    tab_pinned,
    fps_up,
    fps_down,
    logging,
    marker,
    up,
    down,
    left,
    right,
    enter,
    escape,
    backspace,
    other,
};

pub fn resolve(event: zz.KeyEvent) Action {
    return switch (event.key) {
        .up => .up,
        .down => .down,
        .left => .left,
        .right => .right,
        .tab => .next_tab,
        .enter => .enter,
        .escape => .escape,
        .backspace => .backspace,
        .space => .pause,
        .char => |character| switch (character) {
            'q' => .quit,
            '?' => .help,
            'c' => .connect,
            '/' => .filter,
            'p' => .pin,
            't' => .trace,
            'g' => .database_only,
            '1' => .tab_monitor,
            '2' => .tab_transmit,
            '3' => .tab_sent,
            '4' => .tab_plot,
            '5' => .tab_pinned,
            '+' => .fps_up,
            '-' => .fps_down,
            'L' => .logging,
            'm' => .marker,
            else => .other,
        },
        else => .other,
    };
}
